import type { UpgradeDefinition } from '../game/catalog';
import type { TechnologyId, UpgradeId } from '../game/ids';

/** One-time progression card that lets a technology be discovered (effects live on it). */
function progression(
  id: UpgradeId & TechnologyId,
  title: string,
  description: string,
  basePrice: number,
  after: TechnologyId,
): UpgradeDefinition {
  return {
    id,
    title,
    description,
    currency: 'output',
    basePrice,
    priceGrowth: 1,
    maxLevel: 1,
    requires: { technologies: [after] },
    priority: 10,
    discovers: id,
    effectsPerLevel: [],
  };
}

