/**
 * Self-Improvement's own projects: the system starts them in a slot nobody may take; each makes
 * the code a little better (+2 % efficiency), so they are barely worth it.
 */
function internal(id: UpgradeId, title: string, description: string): UpgradeDefinition {
  return {
    id,
    title,
    description,
    currency: 'output',
    basePrice: 0,
    priceGrowth: 1,
    maxLevel: 1,
    requires: { technologies: ['self-improvement'] },
    priority: 90,
    internal: true,
    builtText: `🤖 ${title}: done. Everything is 2 % better and nothing works the same.`,
    effectsPerLevel: [{ kind: 'efficiency', amount: 0.02 }],
  };
}
