/**
 * Third-party notices from the lockfile (`npm run notices`; `-- --check` in `npm run check`):
 * every installed non-dev package with its exact version and declared license. Regenerate after
 * a dependency change. The game's own code is Apache-2.0 (LICENSE); music is licensed per file.
 */
interface LockPackage {
  version?: string;
  license?: string;
  dev?: boolean;
  devOptional?: boolean;
}

export function productionPackages(
  lockText: string,
): { name: string; version: string; license: string }[] {
  const lock = JSON.parse(lockText) as { packages: Record<string, LockPackage> };
  return Object.entries(lock.packages)
    .filter(([key, p]) => key.startsWith('node_modules/') && !p.dev && !p.devOptional)
    .map(([key, p]) => ({
      name: key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length),
      version: p.version ?? '?',
      license: p.license ?? 'UNKNOWN',
    }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function renderNotices(packages: ReturnType<typeof productionPackages>): string {
  const rows = packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`);
  return [
    '# Third-party notices',
    '',
    'Generated by `npm run notices` from `package-lock.json` (installed production dependencies,',
    'including transitive ones). Each package is distributed under its own license, included in',
    'its folder under `node_modules/`. Development-only tools are not shipped and not listed.',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

