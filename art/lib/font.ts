export function textWidth(value: string): number {
  return value.length === 0 ? 0 : value.length * 4 - 1;
}

export function text(c: PixelCanvas, value: string, x: number, y: number, color: Color): void {
  [...value.toUpperCase()].forEach((char, index) => {
    const glyph = GLYPHS[char] ?? GLYPHS['?'] ?? '';
    for (let i = 0; i < 15; i += 1) {
      if (glyph[i] === '1') c.set(x + index * 4 + (i % 3), y + Math.floor(i / 3), color);
    }
  });
}
